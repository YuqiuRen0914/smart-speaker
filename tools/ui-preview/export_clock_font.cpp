// Offline only: use the pinned LVGL TinyTTF rasterizer to preserve the
// existing clock's pixels and metrics in a native, static LVGL font.
#include <lvgl.h>

#include <cassert>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <vector>

namespace {
constexpr char kGlyphs[] = "-0123456789:";

void emit_font(const std::vector<uint8_t> &bytes, const char *name, int size) {
  auto *font = lv_tiny_ttf_create_data_ex(bytes.data(), bytes.size(), size,
                                        LV_FONT_KERNING_NONE, 12);
  assert(font);
  std::vector<lv_font_glyph_dsc_t> metrics;
  std::vector<size_t> offsets;
  size_t offset = 0;
  std::printf("static const uint8_t %s_bitmap[] = {\n", name);
  for (char ch : kGlyphs) {
    if (!ch) break;
    lv_font_glyph_dsc_t glyph{};
    assert(lv_font_get_glyph_dsc(font, &glyph, ch, 0) && !glyph.is_placeholder);
    const auto *bitmap = static_cast<const lv_draw_buf_t *>(lv_font_get_glyph_bitmap(&glyph, nullptr));
    assert(bitmap && bitmap->header.cf == LV_COLOR_FORMAT_A8 &&
           bitmap->header.w == glyph.box_w && bitmap->header.h == glyph.box_h);
    offsets.push_back(offset);
    for (unsigned y = 0; y < glyph.box_h; ++y) {
      const auto *row = bitmap->data + y * bitmap->header.stride;
      std::printf("    ");
      for (unsigned x = 0; x < glyph.box_w; ++x) std::printf("%3u,", unsigned(row[x]));
      std::puts("");
    }
    offset += glyph.box_w * glyph.box_h;
    lv_font_glyph_release_draw_data(&glyph);
    metrics.push_back(glyph);
  }
  std::printf("};\n\nstatic const lv_font_fmt_txt_glyph_dsc_t %s_glyphs[] = {\n    {0},\n", name);
  for (size_t i = 0; i < metrics.size(); ++i) {
    const auto &g = metrics[i];
    std::printf("    {.bitmap_index = %zu, .adv_w = %u, .box_w = %u, .box_h = %u, .ofs_x = %d, .ofs_y = %d}, /* %c */\n",
                offsets[i], unsigned(g.adv_w) * 16, unsigned(g.box_w), unsigned(g.box_h),
                g.ofs_x, g.ofs_y, kGlyphs[i]);
  }
  std::printf(R"(};

static const lv_font_fmt_txt_dsc_t %s_dsc = {
    .glyph_bitmap = %s_bitmap,
    .glyph_dsc = %s_glyphs,
    .cmaps = clock_cmaps,
    .cmap_num = 2,
    .bpp = 8,
    .bitmap_format = LV_FONT_FMT_TXT_PLAIN,
    .stride = 1,
};

const lv_font_t %s = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = %d,
    .base_line = %d,
    .static_bitmap = 1,
    .dsc = &%s_dsc,
};
)", name, name, name, name, font->line_height, font->base_line, name);
  lv_tiny_ttf_destroy(font);
}
}

int main(int argc, char **argv) {
  if (argc != 2) return 2;
  std::ifstream input(argv[1], std::ios::binary);
  const std::vector<uint8_t> bytes((std::istreambuf_iterator<char>(input)), {});
  if (bytes.empty()) return 2;
  lv_init();
  std::puts(R"(/* Generated by tools/ui-preview/export_clock_font.cpp from home_digits.ttf.
 * Modified Teko under SIL OFL 1.1; see THIRD_PARTY_NOTICES.md. */
#include "home_clock_font.h"

static const lv_font_fmt_txt_cmap_t clock_cmaps[] = {
    {.range_start = '-', .range_length = 1, .glyph_id_start = 1, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},
    {.range_start = '0', .range_length = 11, .glyph_id_start = 2, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},
};
)");
  emit_font(bytes, "speaker_home_digits", 100);
  std::puts("");
  emit_font(bytes, "speaker_home_seconds", 42);
  lv_deinit();
}
